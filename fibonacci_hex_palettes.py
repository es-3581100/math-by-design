#!/usr/bin/env python3
"""
Fibonacci HEX Palettes  --  SymPy / NumPy port of
`fibonacci_hex_multispiral_rauzy_geometry_lab.html`

Give it a HEX colour; it gives back a list of palettes generated by every
equation in the original tool:

  * six spiral families on the hexagonal HSV wheel
        φ Fibonacci · τ Tribonacci · δ Silver · ρ Plastic · J Julia · B Binet
    (one colour sampled every quarter-turn -- every 45° for Julia -- along
     the spiral that starts at your colour's position on the wheel)
  * Tribonacci Rauzy tri-tile (tiles A / B / C sampled from the wheel)
  * a palette-geometry report for each palette (PCA shape, hull volume,
    gray spread, null-model comparison)

Where SymPy is used
  - the four ratio constants are the dominant roots of their minimal
    polynomials (x²-x-1, x³-x²-x-1, x²-2x-1, x³-x-1)
  - the spiral equations (log spiral, Julia phase modulation, Binet/Fibonacci
    formula) are written symbolically and `lambdify`-ed into NumPy
  - the Rauzy projection vector (τ², τ, 1) is checked, exactly, to be the
    Perron eigenvector of the Tribonacci substitution matrix

Everything is in the wheel's pixel units (default: the HTML's 600-px canvas,
hexagon circumradius R = 273 px) so node radii match the original tool.

Usage
    python fibonacci_hex_palettes.py "#5CF2B2"
    python fibonacci_hex_palettes.py 5cf2b2 --direction both --count 8
    python fibonacci_hex_palettes.py "#C0392B" --families fibonacci binet --json out.json --html out.html
    python fibonacci_hex_palettes.py --equations
    python fibonacci_hex_palettes.py --self-test

Requires: numpy, sympy.   Optional: scipy (hull volume).
"""
