@dataclass
class Seed:
    hex: str
    rgb: tuple[int, int, int]
    hue: float
    sat: float
    value_in: float
    value_used: float
    theta: float
    r_px: float
    edge_px: float
    auto_direction: str
    radius_px: float
    notes: list[str]


def make_seed(hex_color: str, value: float | None = None, R: float = DEFAULT_R_PX) -> Seed:
    """Invert the wheel: where does this HEX sit (hue = angle, saturation = r/edge)?"""
    rgb = parse_hex(hex_color)
    h, s, v_in = rgb_to_hsv(rgb)
    notes: list[str] = []
    v = v_in if value is None else float(value)
    if value is None and v < VALUE_FLOOR:
        notes.append(f"brightness {v_in:.0%} is below the tool's {VALUE_FLOOR:.0%} minimum; wheel brightness "
                     f"raised to {VALUE_FLOOR:.0%}, so node 00 is a slightly lighter version of your colour "
                     f"(pass --value to override).")
        v = VALUE_FLOOR
    theta = math.radians(h) - HALF_PI
    if max(rgb) == min(rgb):
        theta = -HALF_PI
        notes.append("grey input has no hue: the spiral starts at the wheel's core (hue 0°, top) at the 4-px "
                     "minimum radius, so node 00 is faintly tinted -- same as the HTML.")
    edge = float(edge_radius(theta, R))
    r0 = s * edge
    if r0 < MIN_ANCHOR_PX:
        if max(rgb) != min(rgb):
            notes.append(f"colour is almost grey; start radius raised to the {MIN_ANCHOR_PX:g}-px minimum.")
        r0 = MIN_ANCHOR_PX
    if value is not None and abs(v - v_in) > 1e-9:
        notes.append(f"wheel brightness overridden: {v:.0%} (input was {v_in:.0%}).")
    return Seed(hex_of(rgb), rgb, h, s, v_in, v, theta, r0, edge,
                "in" if r0 / edge >= AUTO_IN_THRESHOLD else "out", R, notes)


def spiral_nodes(fam: Family, seed: Seed, direction: str, bias_pct: float = 0.0) -> dict:
    """Trace one spiral and return its quarter-turn nodes (r, θ), colours and path length."""
    d = 1 if direction == "in" else -1
    R = seed.radius_px
    radius, theta, q = _curves(fam, seed.r_px, seed.theta, d, bias_pct)

    # dense path: runs until it shrinks below 2.4 px (inward) or leaves the hexagon (outward)
    tt = np.arange(fam.max_steps) * fam.dt
    r_path, a_path = radius(tt), theta(tt)
    stop = (r_path < MIN_RADIUS_PX) | ((d < 0) & (r_path > edge_radius(a_path, R)))
    stop[0] = False
    n_keep = int(np.argmax(stop)) if stop.any() else fam.max_steps
    r_path, a_path, tt = r_path[:n_keep], a_path[:n_keep], tt[:n_keep]
    xy = np.stack([r_path * np.cos(a_path), r_path * np.sin(a_path)], 1)
    length = float(np.hypot(*np.diff(xy, axis=0).T).sum()) if n_keep > 1 else 0.0

    # nodes: one per `turn`
    steps = int(math.floor((tt[-1] + 1e-5) / fam.turn))
    idx = np.arange(steps + 1)
    tn = idx * fam.turn
    rn, an = radius(tn), theta(tn)
    ok = ~((rn > edge_radius(an, R) + EDGE_TOL_PX) | (rn < MIN_RADIUS_PX))
    idx, tn, rn, an = idx[ok], tn[ok], rn[ok], an[ok]
    rgb, hue, sat = wheel_sample(rn, an, seed.value_used, R)
    return {"index": idx, "t": tn, "r": rn, "theta": an, "rgb": rgb, "hue": hue, "sat": sat,
            "length": length, "ratio": q}


def _node_label(fam: Family, i: int, t: float) -> str:
    if i == 0:
        return "ORIGIN"
    if fam.kind == "binet":
        return f"F{i + 5}={int(fib(i + 5))} · {i} × 90°"
    if fam.kind == "julia":
        return f"J{i:02d} · {round(math.degrees(t))}°"
    return f"{i} × {round(math.degrees(fam.turn))}°"


def spiral_palette(fam: Family, seed: Seed, direction: str, bias_pct: float = 0.0,
                   count: int | None = None, delta_e_stop: float = DEFAULT_DELTA_E_STOP) -> Palette:
    nd = spiral_nodes(fam, seed, direction, bias_pct)
    raw = [Swatch(hex_of(nd["rgb"][j]), tuple(int(c) for c in nd["rgb"][j]),
                  _node_label(fam, int(nd["index"][j]), float(nd["t"][j])),
                  float(nd["r"][j]), float(nd["hue"][j]), float(nd["sat"][j]))
           for j in range(len(nd["index"]))]
    usable_n, deltas = usable_swatch_prefix(raw, delta_e_stop)
    if count is not None:
        usable_n = min(usable_n, count)
    sw = raw[:usable_n]
    arrow = "inward · edge → core" if direction == "in" else "outward · core → edge"
    ratio_txt = (f"{fam.symbol} = {nd['ratio']:.10f}" if fam.kind != "julia"
                 else f"J / φ = {nd['ratio']:.10f}")
    family_effect = ("90° hue-node skeleton shared by φ/τ/δ/ρ; the ratio changes radial/chroma convergence rate."
                     if fam.kind == "log" else
                     "Julia changes node phase/turn behavior." if fam.kind == "julia" else
                     "Binet uses discrete Fibonacci radii with interpolation.")
    return Palette(fam.key, f"{fam.symbol}  {fam.name} — {arrow}", "spiral", fam.blurb, sw, direction,
                   {"ratio": nd["ratio"], "trace_length_px": nd["length"], "total_nodes": len(nd["index"]),
                    "usable_nodes": usable_n, "delta_e_stop": float(delta_e_stop),
                    "adjacent_delta_e": [float(x) for x in deltas],
                    "stopped_for_delta_e": usable_n < len(raw) and (count is None or usable_n < count),
                    "family_effect": family_effect,
                    "ratio_label": ratio_txt, "turn_deg": math.degrees(fam.turn)})

