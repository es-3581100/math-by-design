GEO_HUES = ["red", "orange", "yellow", "chartreuse", "green", "mint",
            "cyan", "azure", "blue", "violet", "magenta", "rose"]


def _pca(P: np.ndarray):
    mean = P.mean(0)
    D = P - mean
    vals, vecs = np.linalg.eigh(D.T @ D)
    order = np.argsort(vals)[::-1]
    vals = np.clip(vals[order], 0, None)
    vecs = vecs[:, order].T                               # rows = principal axes
    tot = vals.sum()
    f = vals / tot if tot > 0 else np.array([1.0, 0.0, 0.0])
    return mean, vals, vecs, f


def _classify(f, n):
    if n < 2:
        return "NEED 2+ COLORS"
    if n == 2:
        return "SEGMENT"
    if f[0] >= 0.98:
        return "LINE · SPINE"
    if f[2] < 0.0025:
        return "TRIANGLE" if n == 3 else "PLANAR WEDGE"
    if f[2] < 0.04:
        return "FOLDED FAN"
    return "VOLUME · CLOUD"


def _hue_of(rgb) -> float:
    return rgb_to_hsv(rgb)[0] if max(rgb) != min(rgb) else 0.0


def analyze_points(rgbs) -> dict | None:
    P = np.asarray(rgbs, float)
    n = len(P)
    if n == 0:
        return None
    mean, vals, vecs, f = _pca(P)
    vol = 0.0
    if n >= 4 and ConvexHull is not None:
        try:
            vol = float(ConvexHull(P).volume)
        except QhullError:
            vol = 0.0
    gd = np.linalg.norm(P - P.mean(1, keepdims=True), axis=1)       # distance from the gray axis
    gi = int(np.argmax(gd))
    branch = "neutral" if gd[gi] < 8 else GEO_HUES[int(round(_hue_of(P[gi]) / 30)) % 12]
    const_ch = [f"{'RGB'[k]} = {int(P[0, k])}" for k in range(3) if np.all(P[:, k] == P[0, k])]
    mx = P.max(1)
    return {
        "n": n, "mean": mean.tolist(), "shape": _classify(f, n),
        "linearity_pct": float(f[0] * 100), "third_pc_pct": float(f[2] * 100),
        "planarity_pct": float(100 - f[2] * 100),
        "off_plane_max": float(np.abs((P - mean) @ vecs[2]).max()),
        "hull_volume": vol if (n >= 4 and ConvexHull is not None) else None,
        "gray_spread": float(gd[gi]), "gray_branch": branch,
        "pc1_angle_deg": float(math.degrees(math.acos(min(1.0, abs(vecs[0].sum()) / math.sqrt(3))))),
        "face_locked": const_ch,
        "brightness_shell": int(mx[0]) if np.all(mx == mx[0]) and not const_ch else None,
    }


def _third_pc_pct(sets: np.ndarray) -> np.ndarray:
    D = sets - sets.mean(1, keepdims=True)
    w = np.linalg.eigvalsh(np.einsum("tni,tnj->tij", D, D))         # ascending
    w = np.clip(w, 0, None)
    tot = w.sum(1)
    return np.where(tot > 0, w[:, 0] / np.where(tot > 0, tot, 1), 0.0) * 100


def baseline_sets(n: int, value: float, trials: int = 2000) -> dict[str, np.ndarray]:
    """Sorted 3rd-PC variance % for random palettes of n colours (null models)."""
    rng = np.random.default_rng(1234 + n * 97 + int(round(value * 100)))
    out = {}
    out["rgb"] = np.sort(_third_pc_pct(rng.random((trials, n, 3)) * 255))

    need = trials * n                                               # random picks on the hex wheel
    xy = rng.uniform(-1, 1, (need * 3, 2))
    ang = np.arctan2(xy[:, 1], xy[:, 0])
    rad = np.hypot(xy[:, 0], xy[:, 1])
    er = edge_radius(ang, 1.0)
    keep = rad <= er
    xy, ang, rad, er = xy[keep][:need], ang[keep][:need], rad[keep][:need], er[keep][:need]
    rgb = hsv_to_rgb(np.mod((ang + HALF_PI) / TAU2 * 360, 360), np.minimum(1, rad / er), value)
    out["wheel"] = np.sort(_third_pc_pct(rgb.reshape(trials, n, 3).astype(float)))

    k = max(1, n - 1)                                               # neutral ramp + one accent
    ts = np.sort(rng.random((trials, k)) * 255, axis=1)
    ts[:, 0] = rng.random(trials) * 25
    if k > 1:
        ts[:, k - 1] = 220 + rng.random(trials) * 30
    pts = np.clip(ts[..., None] + rng.standard_normal((trials, k, 3)) * 6, 0, 255)
    acc = rng.random((trials, 3)) * 255
    i1 = np.floor(rng.random(trials) * 3).astype(int)
    i2 = (i1 + 1 + np.floor(rng.random(trials) * 2).astype(int)) % 3
    rows = np.arange(trials)
    acc[rows, i1] = 200 + rng.random(trials) * 55
    acc[rows, i2] = rng.random(trials) * 120
    out["ramp"] = np.sort(_third_pc_pct(np.concatenate([pts, acc[:, None, :]], 1)))
    return out


def _stat(sorted_vals: np.ndarray, mine: float) -> dict:
    q = lambda p: float(sorted_vals[min(len(sorted_vals) - 1, int(math.floor(p * (len(sorted_vals) - 1))))])
    flatter = 100.0 * float(np.sum(sorted_vals > mine * (1 + 1e-9) + 1e-12)) / len(sorted_vals)
    return {"median": q(0.5), "p5": q(0.05), "p95": q(0.95), "flatter_than_pct": flatter}


def _verdict(a: dict, st: dict | None) -> str:
    if a["n"] < 3:
        return "Add at least three colors to see a shape."
    bits, f3 = [], a["third_pc_pct"]
    if a["face_locked"]:
        bits.append(f"Face-locked: {', '.join(a['face_locked'])} on every color, so the set lies on one flat face of the RGB cube.")
    elif a["brightness_shell"] is not None:
        bits.append(f"Every color has max(R,G,B) = {a['brightness_shell']}: the set sits on a single brightness shell, "
                    "which is all one wheel brightness can reach.")
    if a["n"] == 3:
        bits.append("Three points always form a flat triangle, so flatness says nothing at n = 3.")
        return " ".join(bits)
    if a["shape"].startswith("LINE"):
        bits.append("Near-linear: the colors move along one axis, like a lightness ramp.")
    elif st:
        if f3 < st["ramp"]["p5"]:
            bits.append("Flatter than almost any neutral ramp + one accent (below its 5th percentile).")
        elif f3 <= st["ramp"]["p95"]:
            bits.append("This flatness is what a neutral ramp plus ONE accent color gives anyway: it follows from "
                        "the construction, not from a hidden pattern.")
        else:
            bits.append("More volume than a neutral ramp + one accent produces, which points to two or more "
                        "independent chroma directions.")
        if "wheel" in st:
            if f3 < st["wheel"]["p5"]:
                bits.append("Flatter than 95% of random wheel picks at this brightness.")
            elif f3 > st["wheel"]["p95"]:
                bits.append("Less flat than 95% of random wheel picks at this brightness.")
            else:
                bits.append("Within the range of random wheel picks at this brightness.")
    return " ".join(bits)


_baseline_cache: dict = {}


def geometry_report(rgbs, value: float, baselines: bool = True, use_wheel_null: bool = True) -> dict | None:
    a = analyze_points(rgbs)
    if a is None or a["n"] < 2:
        return a
    st = None
    if baselines and a["n"] >= 4:
        key = (a["n"], round(value, 2))
        if key not in _baseline_cache:
            _baseline_cache[key] = baseline_sets(a["n"], value)
        sets = _baseline_cache[key]
        f3 = a["third_pc_pct"]
        st = {"rgb": _stat(sets["rgb"], f3), "ramp": _stat(sets["ramp"], f3)}
        if use_wheel_null:
            st["wheel"] = _stat(sets["wheel"], f3)
        a["null_models"] = st
    a["verdict"] = _verdict(a, st)
    return a


