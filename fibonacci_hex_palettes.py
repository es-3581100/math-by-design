def _curves(fam: Family, r0: float, th0: float, d: int, bias_pct: float):
    """Return (radius(t), theta(t), effective_ratio) for one spiral."""
    bias = max(0.2, 1 + bias_pct / 100.0)
    q = fam.ratio * bias
    if fam.kind == "log":
        k = math.log(q) / fam.turn
        return (lambda t: _log_r(t, r0, d, k)), (lambda t: _log_theta(t, th0, d) + 0 * t), q
    if fam.kind == "julia":
        k = math.log(q) / HALF_PI
        c = th0 * 0.73 + 0.61
        return (lambda t: _log_r(t, r0, d, k)), (lambda t: _julia_theta(t, th0, d, c)), q
    # binet: Fibonacci-number radii, log-interpolated, bias applied per turn
    base = float(fib(5))

    def radius(t):
        u = np.asarray(t, float) / fam.turn
        u = np.where(np.abs(u - np.rint(u)) < 1e-9, np.rint(u), u)   # snap exact nodes
        i = np.floor(u)
        f = u - i
        a = fib(5 + i) / base
        b = fib(6 + i) / base
        m = np.exp((1 - f) * np.log(a) + f * np.log(b)) * bias ** u
        return r0 * (1.0 / m if d > 0 else m)

    return radius, (lambda t: _log_theta(t, th0, d) + 0 * t), q


# -- Rauzy: exact check that (τ², τ, 1) is the Perron eigenvector -------------
def rauzy_eigen_check() -> dict:
    """Verify M·v = τ·v exactly, reducing modulo τ³ = τ²+τ+1."""
    T = sp.Symbol("T")
    M = sp.Matrix([[1, 1, 1], [1, 0, 0], [0, 1, 0]])      # σ: 1→12, 2→13, 3→1
    v = sp.Matrix([T**2, T, 1])
    minpoly = sp.Poly(T**3 - T**2 - T - 1, T)
    resid = [sp.rem(sp.Poly(sp.expand(e), T), minpoly) for e in (M * v - T * v)]
    return {"matrix": M, "eigenvector": v, "residual_zero": all(r.is_zero for r in resid),
            "char_poly": M.charpoly(T).as_expr()}


