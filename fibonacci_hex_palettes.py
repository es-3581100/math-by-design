X = sp.Symbol("x")

RATIO_POLYS = {            # key -> (symbol, minimal polynomial)
    "fibonacci": ("φ", X**2 - X - 1),
    "tribonacci": ("τ", X**3 - X**2 - X - 1),
    "silver": ("δ", X**2 - 2 * X - 1),
    "plastic": ("ρ", X**3 - X - 1),
}


def _dominant_root(poly: sp.Expr) -> sp.Expr:
    roots = sp.real_roots(sp.Poly(poly, X))
    return max(roots, key=lambda r: float(r.evalf(30)))


RATIO_EXACT = {k: _dominant_root(p) for k, (_, p) in RATIO_POLYS.items()}
RATIO = {k: float(v.evalf(30)) for k, v in RATIO_EXACT.items()}
PHI = RATIO["fibonacci"]
TRIBONACCI = RATIO["tribonacci"]

# -- spiral equations (symbolic) ------------------------------------------
t_, r0_, th0_, d_, k_, c_ = sp.symbols("t r_0 theta_0 d k c", real=True)
q_ = sp.Symbol("q", positive=True)

# d = +1 spirals inward (edge -> core), d = -1 outward (core -> edge)
LOG_K = sp.log(q_) / (sp.pi / 2)                      # k = ln(q) / quarter-turn
LOG_R = r0_ * sp.exp(-d_ * k_ * t_)                   # r(t) = r0 e^(-d k t)
LOG_THETA = th0_ + d_ * t_                            # θ(t) = θ0 + d t

_u = th0_ + d_ * t_
JULIA_PHASE = (sp.Rational(13, 100) * sp.sin(2 * _u + c_)
               + sp.Rational(11, 200) * sp.sin(4 * _u - c_)
               + sp.Rational(1, 40) * sp.sin(8 * _u + sp.Rational(17, 10) * c_))
JULIA_THETA = th0_ + d_ * t_ + JULIA_PHASE            # θ(t) = θ0 + d t + φ(t)
JULIA_C = th0_ * sp.Rational(73, 100) + sp.Rational(61, 100)

n_ = sp.Symbol("n", integer=True)
_phi_sym = (1 + sp.sqrt(5)) / 2
BINET = (_phi_sym**n_ - (-1 / _phi_sym)**n_) / sp.sqrt(5)   # F(n)

_log_r = sp.lambdify((t_, r0_, d_, k_), LOG_R, "numpy")
_log_theta = sp.lambdify((t_, th0_, d_), LOG_THETA, "numpy")
_julia_theta = sp.lambdify((t_, th0_, d_, c_), JULIA_THETA, "numpy")
_binet = sp.lambdify(n_, BINET, "numpy")


def fib(n):
    """Fibonacci numbers from Binet's closed form (rounded, as in the HTML)."""
    return np.floor(_binet(np.asarray(n, dtype=float)) + 0.5)


