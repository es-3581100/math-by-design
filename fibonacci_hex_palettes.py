def edge_radius(theta, R=DEFAULT_R_PX):
    """Distance from wheel centre to the hexagon edge in direction θ."""
    diff = np.mod(np.asarray(theta, float) + math.pi / 3 + math.pi / 6, math.pi / 3) - math.pi / 6
    return R * (math.sqrt(3) / 2) / np.cos(diff)


def hsv_to_rgb(h, s, v):
    """HSV -> RGB ints, matching the HTML's rounding (round half up)."""
    h, s, v = np.broadcast_arrays(np.asarray(h, float), np.asarray(s, float), np.asarray(v, float))
    a = np.mod(h, 360.0) / 60.0
    c = s
    x = c * (1 - np.abs(np.mod(a, 2) - 1))
    m = 1 - c
    z = np.zeros_like(a)
    conds = [a < 1, a < 2, a < 3, a < 4, a < 5]
    rr = np.select(conds, [c, x, z, z, x], default=c)
    gg = np.select(conds, [x, c, c, x, z], default=z)
    bb = np.select(conds, [z, z, x, c, c], default=x)
    rgb = (np.stack([rr, gg, bb], -1) + m[..., None]) * 255.0 * v[..., None]
    return np.clip(np.floor(rgb + 0.5), 0, 255).astype(int)


def rgb_to_hsv(rgb: Sequence[int]):
    r, g, b = (c / 255.0 for c in rgb)
    mx, mn = max(r, g, b), min(r, g, b)
    dl = mx - mn
    if dl == 0:
        h = 0.0
    elif mx == r:
        h = 60 * (((g - b) / dl) % 6)
    elif mx == g:
        h = 60 * ((b - r) / dl + 2)
    else:
        h = 60 * ((r - g) / dl + 4)
    return h, (0.0 if mx == 0 else dl / mx), mx


def hex_of(rgb) -> str:
    return "#%02X%02X%02X" % tuple(int(c) for c in rgb)


def parse_hex(text: str) -> tuple[int, int, int]:
    m = re.fullmatch(r"\s*#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})\s*", text or "")
    if not m:
        raise ValueError(f"not a HEX colour: {text!r} (use #RRGGBB or #RGB)")
    h = m.group(1)
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)



def rgb_to_lab(rgb: Sequence[int]) -> np.ndarray:
    """sRGB (0..255) -> CIE L*a*b* (D65), for perceptual convergence checks."""
    x = np.asarray(rgb, dtype=float) / 255.0
    x = np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)
    X, Y, Z = np.array([
        0.4124564 * x[0] + 0.3575761 * x[1] + 0.1804375 * x[2],
        0.2126729 * x[0] + 0.7151522 * x[1] + 0.0721750 * x[2],
        0.0193339 * x[0] + 0.1191920 * x[1] + 0.9503041 * x[2],
    ]) / np.array([0.95047, 1.0, 1.08883])
    eps, kappa = 216 / 24389, 24389 / 27
    f = lambda t: t ** (1 / 3) if t > eps else (kappa * t + 16) / 116
    fx, fy, fz = f(X), f(Y), f(Z)
    return np.array([116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)])


def delta_e76(a: Sequence[int], b: Sequence[int]) -> float:
    """CIE76 ΔE. Used only to decide when further convergence nodes stop adding useful separation."""
    return float(np.linalg.norm(rgb_to_lab(a) - rgb_to_lab(b)))


def usable_swatch_prefix(swatches: Sequence["Swatch"], threshold: float = DEFAULT_DELTA_E_STOP) -> tuple[int, list[float]]:
    """Return count before first adjacent ΔE<threshold, plus all adjacent ΔE values measured."""
    if len(swatches) < 2:
        return len(swatches), []
    deltas = [delta_e76(swatches[i - 1].rgb, swatches[i].rgb) for i in range(1, len(swatches))]
    for i, de in enumerate(deltas, start=1):
        if de < threshold:
            return i, deltas
    return len(swatches), deltas


def parse_hex_list(text: str, limit: int = 40) -> list[str]:
    """Pull #RRGGBB / #RGB / bare RRGGBB colours out of arbitrary text."""
    out, seen = [], set()
    for m in re.finditer(r"#([0-9a-f]{6}|[0-9a-f]{3})(?![0-9a-f])|\b([0-9a-f]{6})\b", str(text), re.I):
        h = m.group(1) or m.group(2)
        if not m.group(1) and h.isdigit():
            continue                      # bare all-digit runs are numbers
        if len(h) == 3:
            h = "".join(ch * 2 for ch in h)
        h = "#" + h.upper()
        if h not in seen:
            seen.add(h)
            out.append(h)
    return out[:limit]


def wheel_sample(r, theta, value, R=DEFAULT_R_PX):
    """Colour at polar position (r px, θ rad) on the wheel at brightness `value`."""
    r = np.asarray(r, float)
    theta = np.asarray(theta, float)
    sat = np.clip(r / edge_radius(theta, R), 0, 1)
    hue = np.mod(np.mod((theta + HALF_PI) / TAU2 * 360.0, 360.0) + 360.0, 360.0)
    return hsv_to_rgb(hue, sat, value), hue, sat


